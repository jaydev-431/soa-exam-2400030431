import React, { useEffect, useState } from "react";
import axios from "axios";

export default function BusRoute() {
  // Backend URL
  const API_URL = "http://localhost:8083/crudservice";

  // All states
  const [routes, setRoutes] = useState([]);
  const [formData, setFormData] = useState({
    routeNumber: "",
    startPoint: "",
    endPoint: "",
    distanceKm: "",
  });
  const [searchId, setSearchId] = useState("");
  const [searchResult, setSearchResult] = useState(null);
  const [editId, setEditId] = useState(null);
  const [errors, setErrors] = useState({});
  const [message, setMessage] = useState("");
  const [messageType, setMessageType] = useState("success");
  const [loading, setLoading] = useState(false);
  const [saving, setSaving] = useState(false);
  const [deletingId, setDeletingId] = useState(null);

  // Display all bus routes
  const displayAll = async () => {
    setLoading(true);

    try {
      const response = await axios.get(`${API_URL}/displayall`);
      setRoutes(Array.isArray(response.data) ? response.data : []);
    } catch (error) {
      setMessage(
        error.response
          ? `Unable to load routes. HTTP ${error.response.status}.`
          : "Cannot connect to the backend on port 8003."
      );
      setMessageType("error");
    } finally {
      setLoading(false);
    }
  };

  // Load records when the component opens
  useEffect(() => {
    displayAll();
  }, []);

  // Handle form changes
  const handleChange = (e) => {
    const { name, value } = e.target;

    setFormData((previous) => ({
      ...previous,
      [name]: value,
    }));

    setErrors((previous) => ({
      ...previous,
      [name]: "",
    }));
  };

  // Validate form fields
  const validateForm = () => {
    const newErrors = {};

    if (!formData.routeNumber.trim()) {
      newErrors.routeNumber = "Route number is required.";
    } else if (formData.routeNumber.trim().length > 50) {
      newErrors.routeNumber = "Route number cannot exceed 50 characters.";
    }

    if (!formData.startPoint.trim()) {
      newErrors.startPoint = "Starting point is required.";
    }

    if (!formData.endPoint.trim()) {
      newErrors.endPoint = "Ending point is required.";
    }

    if (
      formData.distanceKm.trim() === "" ||
      !Number.isFinite(Number(formData.distanceKm)) ||
      Number(formData.distanceKm) <= 0
    ) {
      newErrors.distanceKm = "Distance must be greater than zero.";
    }

    setErrors(newErrors);
    return Object.keys(newErrors).length === 0;
  };

  // Add or update a route
  const handleSubmit = async (e) => {
    e.preventDefault();

    if (!validateForm()) return;

    setSaving(true);
    setMessage("");

    // Match the BusRouteDto fields. ID is generated by the backend.
    const payload = {
      routeNumber: formData.routeNumber.trim(),
      startPoint: formData.startPoint.trim(),
      endPoint: formData.endPoint.trim(),
      distanceKm: Number(formData.distanceKm),
    };

    try {
      if (editId !== null) {
        await axios.put(`${API_URL}/update/${editId}`, payload);
        setMessage("Bus route updated successfully.");
      } else {
        await axios.post(`${API_URL}/add`, payload);
        setMessage("Bus route added successfully.");
      }

      setMessageType("success");
      resetForm();
      await displayAll();
    } catch (error) {
      setMessage(
        typeof error.response?.data === "string"
          ? error.response.data
          : error.response?.data?.message ||
            "Unable to save the bus route."
      );
      setMessageType("error");
    } finally {
      setSaving(false);
    }
  };

  // Fetch a route by ID
  const fetchById = async (e) => {
    e.preventDefault();

    if (!searchId.trim() || !Number.isInteger(Number(searchId)) ||
        Number(searchId) <= 0) {
      setMessage("Please enter a valid route ID.");
      setMessageType("error");
      setSearchResult(null);
      return;
    }

    setMessage("");

    try {
      const response = await axios.get(
        `${API_URL}/display/${searchId.trim()}`
      );

      setSearchResult(response.data);
      setMessage("Bus route found.");
      setMessageType("success");
    } catch (error) {
      setSearchResult(null);
      setMessage(
        error.response?.status === 404
          ? "No bus route found with that ID."
          : "Unable to fetch the route. Please check the backend."
      );
      setMessageType("error");
    }
  };

  // Load a route into the form for editing
  const editRoute = (route) => {
    setEditId(route.id);

    setFormData({
      routeNumber: route.routeNumber ?? "",
      startPoint: route.startPoint ?? "",
      endPoint: route.endPoint ?? "",
      distanceKm:
        route.distanceKm == null ? "" : String(route.distanceKm),
    });

    setErrors({});
    setMessage("");
    window.scrollTo({ top: 0, behavior: "smooth" });
  };

  // Delete a route
  const deleteRoute = async (id) => {
    if (!window.confirm("Are you sure you want to delete this bus route?")) {
      return;
    }

    setDeletingId(id);
    setMessage("");

    try {
      const response = await axios.delete(`${API_URL}/delete/${id}`);

      setMessage(
        typeof response.data === "string"
          ? response.data
          : "Bus route deleted successfully."
      );
      setMessageType("success");

      if (editId === id) resetForm();
      if (searchResult?.id === id) setSearchResult(null);

      await displayAll();
    } catch (error) {
      setMessage(
        typeof error.response?.data === "string"
          ? error.response.data
          : "Unable to delete the bus route."
      );
      setMessageType("error");
    } finally {
      setDeletingId(null);
    }
  };

  // Reset the form
  const resetForm = () => {
    setEditId(null);
    setFormData({
      routeNumber: "",
      startPoint: "",
      endPoint: "",
      distanceKm: "",
    });
    setErrors({});
  };

  // Reusable Tailwind classes
  const inputClass =
    "w-full rounded-lg border border-slate-300 px-4 py-3 text-slate-800 outline-none transition focus:border-blue-500 focus:ring-2 focus:ring-blue-100";

  return (
    <main className="min-h-screen bg-slate-100 px-4 py-8 sm:px-8">
      <div className="mx-auto max-w-7xl space-y-6">

        {/* Page heading */}
        <header>
          <p className="text-sm font-bold uppercase tracking-widest text-blue-600">
            Bus Route Management
          </p>
          <h1 className="mt-2 text-4xl font-bold text-slate-900">
            Bus routes
          </h1>
          <p className="mt-2 text-slate-500">
            Manage the route records registered with your service.
          </p>
        </header>

        {/* Success and error messages */}
        {message && (
          <div
            role="alert"
            className={`flex items-center justify-between rounded-xl border p-4 ${
              messageType === "error"
                ? "border-red-200 bg-red-50 text-red-700"
                : "border-green-200 bg-green-50 text-green-700"
            }`}
          >
            <span>{message}</span>
            <button
              type="button"
              onClick={() => setMessage("")}
              className="ml-3 text-xl"
              aria-label="Dismiss message"
            >
              ×
            </button>
          </div>
        )}

        {/* Fetch by ID */}
        <section className="rounded-2xl bg-white p-6 shadow-sm sm:p-8">
          <h2 className="mb-5 text-xl font-bold text-slate-800">
            Get Bus Route By ID
          </h2>

          <form
            onSubmit={fetchById}
            className="flex flex-col gap-3 sm:flex-row"
          >
            <input
              type="number"
              min="1"
              step="1"
              value={searchId}
              onChange={(e) => setSearchId(e.target.value)}
              placeholder="Enter route ID"
              className={`${inputClass} sm:max-w-sm`}
            />

            <button
              type="submit"
              className="rounded-lg bg-blue-600 px-6 py-3 font-semibold text-white hover:bg-blue-700"
            >
              Fetch
            </button>
          </form>

          {searchResult && (
            <div className="mt-5 rounded-xl border border-blue-100 bg-blue-50 p-5">
              <h3 className="mb-3 font-bold text-slate-800">
                Route details
              </h3>
              <div className="grid gap-2 sm:grid-cols-2">
                <p><strong>ID:</strong> {searchResult.id}</p>
                <p><strong>Route number:</strong> {searchResult.routeNumber}</p>
                <p><strong>Start point:</strong> {searchResult.startPoint}</p>
                <p><strong>End point:</strong> {searchResult.endPoint}</p>
                <p><strong>Distance:</strong> {searchResult.distanceKm} km</p>
              </div>
            </div>
          )}
        </section>

        {/* Add and update form */}
        <section className="rounded-2xl bg-white p-6 shadow-sm sm:p-8">
          <div className="mb-6 flex items-center justify-between gap-3">
            <h2 className="text-xl font-bold text-slate-800">
              {editId !== null ? "Edit Bus Route" : "Add New Bus Route"}
            </h2>

            {editId !== null && (
              <button
                type="button"
                onClick={resetForm}
                className="text-sm font-semibold text-slate-500 hover:text-slate-900"
              >
                Cancel edit
              </button>
            )}
          </div>

          <form onSubmit={handleSubmit} className="space-y-5">
            <div className="grid gap-5 sm:grid-cols-2">
              {[
                ["routeNumber", "Route Number", "Enter route number"],
                ["startPoint", "Start Point", "Enter starting point"],
                ["endPoint", "End Point", "Enter ending point"],
                ["distanceKm", "Distance (km)", "Enter distance in km"],
              ].map(([name, label, placeholder]) => (
                <div key={name}>
                  <label
                    htmlFor={name}
                    className="mb-2 block text-sm font-semibold text-slate-700"
                  >
                    {label}
                  </label>

                  <input
                    id={name}
                    name={name}
                    type={name === "distanceKm" ? "number" : "text"}
                    min={name === "distanceKm" ? "0.01" : undefined}
                    step={name === "distanceKm" ? "any" : undefined}
                    value={formData[name]}
                    onChange={handleChange}
                    placeholder={placeholder}
                    className={`${inputClass} ${
                      errors[name] ? "border-red-500" : ""
                    }`}
                  />

                  {errors[name] && (
                    <p className="mt-1 text-sm text-red-600">
                      {errors[name]}
                    </p>
                  )}
                </div>
              ))}
            </div>

            <button
              type="submit"
              disabled={saving}
              className="rounded-lg bg-blue-600 px-6 py-3 font-semibold text-white transition hover:bg-blue-700 disabled:cursor-not-allowed disabled:opacity-60"
            >
              {saving
                ? "Saving..."
                : editId !== null
                  ? "Update Route"
                  : "Add Route"}
            </button>
          </form>
        </section>

        {/* Display all routes */}
        <section className="rounded-2xl bg-white p-6 shadow-sm sm:p-8">
          <div className="mb-6 flex flex-wrap items-center justify-between gap-3">
            <h2 className="text-xl font-bold text-slate-800">
              All Bus Routes
            </h2>

            <button
              type="button"
              onClick={displayAll}
              disabled={loading}
              className="rounded-lg border border-slate-300 px-4 py-2 font-semibold text-slate-700 hover:bg-slate-50 disabled:opacity-60"
            >
              {loading ? "Loading..." : "Refresh"}
            </button>
          </div>

          {loading ? (
            <p className="py-10 text-center text-slate-500">
              Loading bus routes...
            </p>
          ) : routes.length === 0 ? (
            <p className="rounded-xl bg-slate-50 py-10 text-center text-slate-500">
              No bus routes found. Add your first route above.
            </p>
          ) : (
            <div className="overflow-x-auto">
              <table className="w-full min-w-[700px] border-collapse text-left">
                <thead className="bg-slate-800 text-white">
                  <tr>
                    {[
                      "ID",
                      "Route Number",
                      "Start Point",
                      "End Point",
                      "Distance (km)",
                      "Actions",
                    ].map((heading) => (
                      <th
                        key={heading}
                        className="px-4 py-4 text-sm font-semibold"
                      >
                        {heading}
                      </th>
                    ))}
                  </tr>
                </thead>

                <tbody>
                  {routes.map((route) => (
                    <tr
                      key={route.id}
                      className="border-b border-slate-100 transition hover:bg-slate-50"
                    >
                      <td className="px-4 py-4">{route.id}</td>
                      <td className="px-4 py-4 font-medium text-slate-800">
                        {route.routeNumber}
                      </td>
                      <td className="px-4 py-4">{route.startPoint}</td>
                      <td className="px-4 py-4">{route.endPoint}</td>
                      <td className="px-4 py-4">{route.distanceKm}</td>
                      <td className="px-4 py-4">
                        <div className="flex gap-2">
                          <button
                            type="button"
                            onClick={() => editRoute(route)}
                            className="rounded-md bg-green-600 px-3 py-2 text-sm font-semibold text-white hover:bg-green-700"
                          >
                            Edit
                          </button>

                          <button
                            type="button"
                            disabled={deletingId === route.id}
                            onClick={() => deleteRoute(route.id)}
                            className="rounded-md bg-red-600 px-3 py-2 text-sm font-semibold text-white hover:bg-red-700 disabled:opacity-60"
                          >
                            {deletingId === route.id ? "Deleting..." : "Delete"}
                          </button>
                        </div>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </section>
      </div>
    </main>
  );
}